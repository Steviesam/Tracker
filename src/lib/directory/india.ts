/**
 * Place names, so the State and City filters hold what their labels promise.
 *
 * Sheets maintained by several people do not keep the two apart. A block may have a City
 * column and no State at all; another writes "CHENNAI" under State; a third puts
 * "Mumbai, Maharashtra" in one cell. Filed as-is, the State filter fills with cities and
 * the City filter with states, and neither is usable.
 *
 * Everything here is a lookup of a fixed, public fact — Chennai is in Tamil Nadu — not a
 * guess about a creator. A state is only ever *derived* when the sheet gave none; a state
 * the sheet states is never overruled.
 */

/** Comparison key: case, spacing and punctuation all vary, none of them meaningfully. */
function key(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]/g, "");
}


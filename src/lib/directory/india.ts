const CITY_STATE = new Map<string, string>();
const CITY_LABEL = new Map<string, string>();

for (const [state, cities] of Object.entries(CITIES)) {
  for (const city of cities) {
    CITY_STATE.set(key(city), state);
    CITY_LABEL.set(key(city), city);
  }
}

for (const [alias, canonical] of Object.entries(CITY_RENAMES)) {
  CITY_LABEL.set(key(alias), canonical);
  const state = CITY_STATE.get(key(canonical));
  if (state) CITY_STATE.set(key(alias), state);
}

/** The canonical state name for a value, or null when it names no state we know. */
export function canonicalState(value: string): string | null {
  return STATE_BY_KEY.get(key(value)) ?? null;
}

/** The state a city sits in, or null when the city is unknown or shared between states. */
export function stateForCity(value: string): string | null {
  return CITY_STATE.get(key(value)) ?? null;
}

/** The city's current official name, for values we recognise. */
export function canonicalCity(value: string): string | null {
  return CITY_LABEL.get(key(value)) ?? null;
}
